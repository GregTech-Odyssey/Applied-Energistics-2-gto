	private PlannerText() {
	}

	public static String tr(String key, String english) {
		String translationKey = "emi.production_planner." + key;
		String translated = null;
		try {
			if (I18n.exists(translationKey)) {
				translated = I18n.get(translationKey);
			}
		} catch (Throwable ignored) {
		}

		if (isRussian()) {
			if (translated != null && !translated.equals(english) && !translated.equals(translationKey)) {
				return translated;
			}
			String builtIn = RU.get(key);
			if (builtIn != null) {
				return builtIn;
			}
			String compat = PlannerMachineCompatRegistry.russianText(key);
			if (compat != null) {
				return compat;
			}
		}

		return translated != null && !translated.equals(translationKey) ? translated : english;
	}

	public static String tr(String key, String english, Object... args) {
		return String.format(tr(key, english), args);
	}

	public static boolean isRussian() {
		try {
			String language = Minecraft.getInstance().getLanguageManager().getSelected();
			return language != null && language.toLowerCase().startsWith("ru");
		} catch (Throwable ignored) {
			return false;
		}
	}
